// ---------------------------------------------------------------- 解析与归一化

export interface PromptSettingsLike {
  activePromptId?: string
  customPrompts?: PromptPreset[]
}

export function isUserPromptId(id: string): boolean {
  return id.startsWith(USER_PROMPT_PREFIX)
}

/** 生成新的用户方案 id（形如 User-<36进制时间戳>-<随机>，天然不与内置 id 冲突） */
export function newUserPromptId(): string {
  const rand = Math.random().toString(36).slice(2, 8)
  return `${USER_PROMPT_PREFIX}-${Date.now().toString(36)}-${rand}`
}

/** 归一化用户方案：缺 id 自动生成；非 User 前缀强制补前缀；去空内容、去重复 id */
export function normalizeCustomPrompts(raw: unknown): PromptPreset[] {
  if (!Array.isArray(raw)) return []
  const out: PromptPreset[] = []
  const seen = new Set<string>()
  for (const item of raw) {
    if (typeof item !== 'object' || item === null) continue
    const r = item as Record<string, unknown>
    const content = typeof r.content === 'string' ? r.content : ''
    if (!content.trim()) continue
    let id = typeof r.id === 'string' ? r.id.trim() : ''
    if (!id) id = newUserPromptId()
    if (!isUserPromptId(id)) id = `${USER_PROMPT_PREFIX}-${id}`
    if (seen.has(id)) continue
    seen.add(id)
    const name = typeof r.name === 'string' ? r.name.trim() : ''
    out.push({ id, name: name || '自定义方案', content })
  }
  return out
}

/**
 * 全部可选方案：内置 + 用户自定义。
 * 注意：这里**不再重新归一化**——归一化只在配置加载时做一次；否则用户在设置页把内容清空的瞬间，
 * 方案会被当作「空方案」丢弃而突然消失。
 */
export function listPromptPresets(m: PromptSettingsLike): PromptPreset[] {
  const custom = Array.isArray(m.customPrompts) ? m.customPrompts : []
  return [...DEFAULT_PROMPT_PRESETS, ...custom]
}

/** 当前生效方案；id 缺失/失效时回落内置「通用图片」 */
export function resolveActivePromptPreset(m: PromptSettingsLike): PromptPreset {
  const all = listPromptPresets(m)
  const id = (m.activePromptId ?? '').trim()
  return all.find((p) => p.id === id) ?? all[0]
}

/** 当前生效方案的 user 段正文（空则回落基线） */
export function resolveActivePromptContent(m: PromptSettingsLike): string {
  const text = resolveActivePromptPreset(m).content.trim()
  return text || DEFAULT_USER_PROMPT
}

// ---------------------------------------------------------------- 旧接口（兼容）

export interface ResolvedPrompt {
  system: string
  user: string
}

/**
 * 解析最终双段 Prompt（T2-02 兼容入口）：
 * - 空/空白 → 默认 user 段；非空白 → 覆盖 user 段；system 恒定。
 */
export function resolvePrompt(customUserPrompt?: string): ResolvedPrompt {
  const custom = (customUserPrompt ?? '').trim()
  return {
    system: DEFAULT_SYSTEM_PROMPT,
    user: custom || DEFAULT_USER_PROMPT,
  }
}
